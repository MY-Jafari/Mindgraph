import { format } from 'sql-formatter';
import type { DBTable, DBColumn, DBRelationship, SQLDialect } from '@/features/projects/types';

export interface DDLOptions {
  dialect?: SQLDialect;
  dropIfExists?: boolean;
  ifNotExists?: boolean;
  quotedIdentifiers?: boolean;
  inlineForeignKeys?: boolean;
}

function quoteId(name: string, dialect: SQLDialect, quoted: boolean): string {
  if (!quoted) return name;
  switch (dialect) {
    case 'mysql':
    case 'mariadb':
      return `\`${name.replace(/`/g, '``')}\``;
    case 'sqlserver':
      return `[${name.replace(/]/g, ']]')}]`;
    case 'oracle':
    case 'postgresql':
    case 'sqlite':
    default:
      return `"${name.replace(/"/g, '""')}"`;
  }
}

function qualifiedTableName(table: DBTable, dialect: SQLDialect, quoted: boolean): string {
  const tableName = quoteId(table.name, dialect, quoted);
  return table.schema ? `${quoteId(table.schema, dialect, quoted)}.${tableName}` : tableName;
}

function supportsIfNotExists(dialect: SQLDialect): boolean {
  return ['postgresql', 'mysql', 'mariadb', 'sqlite'].includes(dialect);
}

function getPrimaryKeyNames(table: DBTable): string[] {
  const columnNames = new Set(table.columns.map((column) => column.name));
  const explicit = (table.primaryKey || []).filter((name) => columnNames.has(name));
  if (explicit.length > 0) return explicit;
  return table.columns.filter((column) => column.isPrimaryKey).map((column) => column.name);
}

function columnDefinition(
  table: DBTable,
  column: DBColumn,
  dialect: SQLDialect,
  quoted: boolean,
  primaryKeyNames: string[],
  relationships: DBRelationship[],
  tables: DBTable[],
  inlineFK: boolean
): string {
  const colName = quoteId(column.name, dialect, quoted);
  const isPrimary = primaryKeyNames.includes(column.name);
  const compositePrimary = primaryKeyNames.length > 1;
  const upperType = column.type.trim().toUpperCase();

  let def = `${colName} ${column.type}`;

  if (column.isAutoIncrement) {
    if (dialect === 'sqlite') {
      if (isPrimary && (upperType.includes('INT') || upperType === '')) {
        def = `${colName} INTEGER PRIMARY KEY AUTOINCREMENT`;
      } else if (isPrimary) {
        def += ' PRIMARY KEY';
      }
    } else if (dialect === 'mysql' || dialect === 'mariadb') {
      def += ' AUTO_INCREMENT';
    } else if (dialect === 'sqlserver') {
      def += ' IDENTITY(1,1)';
    } else if (dialect === 'oracle') {
      def += ' GENERATED BY DEFAULT AS IDENTITY';
    } else if (dialect === 'postgresql' && !upperType.includes('SERIAL')) {
      def += ' GENERATED BY DEFAULT AS IDENTITY';
    }
  }

  if (isPrimary && !compositePrimary && !(dialect === 'sqlite' && column.isAutoIncrement)) {
    def += ' PRIMARY KEY';
  }

  if (column.isUnique && !isPrimary) {
    def += ' UNIQUE';
  }

  if (column.isNullable === false) {
    def += ' NOT NULL';
  }

  if (column.defaultValue !== undefined && column.defaultValue !== '') {
    def += ` DEFAULT ${column.defaultValue}`;
  }

  if (column.checkConstraint) {
    def += ` CHECK (${column.checkConstraint})`;
  }

  if (inlineFK) {
    const rel = relationships.find(
      (relationship) =>
        relationship.sourceTableId === table.id && relationship.sourceColumnId === column.id
    );
    if (rel) {
      const targetTable = tables.find((candidate) => candidate.id === rel.targetTableId);
      const targetColumn = targetTable?.columns.find(
        (candidate) => candidate.id === rel.targetColumnId
      );
      if (targetTable && targetColumn) {
        const targetTableName = qualifiedTableName(targetTable, dialect, quoted);
        const targetColumnName = quoteId(targetColumn.name, dialect, quoted);
        def += ` REFERENCES ${targetTableName} (${targetColumnName})`;
        if (rel.onDelete) def += ` ON DELETE ${rel.onDelete}`;
        if (rel.onUpdate) def += ` ON UPDATE ${rel.onUpdate}`;
      }
    }
  }

  return def;
}

/**
 * Generates SQL DDL with per-dialect syntax. SQL Server and Oracle do not
 * support `CREATE TABLE IF NOT EXISTS`; SQLite only supports AUTOINCREMENT on
 * `INTEGER PRIMARY KEY`; composite primary keys are emitted as table
 * constraints rather than repeated inline PRIMARY KEY clauses.
 */
export function generateDDL(
  tables: DBTable[],
  relationships: DBRelationship[],
  options: DDLOptions = {}
): string {
  const dialect = options.dialect || 'postgresql';
  const dropIfExists = options.dropIfExists ?? false;
  const ifNotExists = options.ifNotExists ?? true;
  const quoted = options.quotedIdentifiers ?? false;
  const inlineFK = options.inlineForeignKeys ?? false;

  const ddlStatements: string[] = [];

  if (dropIfExists) {
    for (const table of [...tables].reverse()) {
      const name = qualifiedTableName(table, dialect, quoted);
      if (dialect === 'postgresql') {
        ddlStatements.push(`DROP TABLE IF EXISTS ${name} CASCADE;`);
      } else if (dialect === 'oracle') {
        ddlStatements.push(`DROP TABLE ${name} CASCADE CONSTRAINTS;`);
      } else if (dialect === 'sqlserver') {
        const objectName = name.replace(/'/g, "''");
        ddlStatements.push(`IF OBJECT_ID(N'${objectName}', N'U') IS NOT NULL DROP TABLE ${name};`);
      } else {
        ddlStatements.push(`DROP TABLE IF EXISTS ${name};`);
      }
    }
  }

  for (const table of tables) {
    const tableName = qualifiedTableName(table, dialect, quoted);
    const useIfNotExists = ifNotExists && supportsIfNotExists(dialect);
    const primaryKeyNames = getPrimaryKeyNames(table);
    const columnDefs = table.columns.map((column) =>
      columnDefinition(
        table,
        column,
        dialect,
        quoted,
        primaryKeyNames,
        relationships,
        tables,
        inlineFK
      )
    );

    const tableConstraints: string[] = [];
    if (primaryKeyNames.length > 1) {
      tableConstraints.push(
        `PRIMARY KEY (${primaryKeyNames.map((name) => quoteId(name, dialect, quoted)).join(', ')})`
      );
    }
    for (const unique of table.uniqueConstraints || []) {
      const nameClause = unique.name ? `CONSTRAINT ${quoteId(unique.name, dialect, quoted)} ` : '';
      tableConstraints.push(
        `${nameClause}UNIQUE (${unique.columns
          .map((name) => quoteId(name, dialect, quoted))
          .join(', ')})`
      );
    }
    for (const check of table.checkConstraints || []) {
      const nameClause = check.name ? `CONSTRAINT ${quoteId(check.name, dialect, quoted)} ` : '';
      tableConstraints.push(`${nameClause}CHECK (${check.expression})`);
    }

    const lines = [...columnDefs, ...tableConstraints];
    ddlStatements.push(
      `CREATE TABLE ${useIfNotExists ? 'IF NOT EXISTS ' : ''}${tableName} (\n  ${lines.join(
        ',\n  '
      )}\n);`
    );

    for (const index of table.indexes || []) {
      const unique = index.isUnique ? 'UNIQUE ' : '';
      const indexName = quoteId(index.name, dialect, quoted);
      const columns = index.columns.map((name) => quoteId(name, dialect, quoted)).join(', ');
      ddlStatements.push(`CREATE ${unique}INDEX ${indexName} ON ${tableName} (${columns});`);
    }
  }

  if (!inlineFK) {
    let fkIndex = 0;
    for (const rel of relationships) {
      const sourceTable = tables.find((table) => table.id === rel.sourceTableId);
      const targetTable = tables.find((table) => table.id === rel.targetTableId);
      const sourceColumn = sourceTable?.columns.find((column) => column.id === rel.sourceColumnId);
      const targetColumn = targetTable?.columns.find((column) => column.id === rel.targetColumnId);

      if (!sourceTable || !targetTable || !sourceColumn || !targetColumn) continue;

      const sourceTableName = qualifiedTableName(sourceTable, dialect, quoted);
      const targetTableName = qualifiedTableName(targetTable, dialect, quoted);
      const sourceColumnName = quoteId(sourceColumn.name, dialect, quoted);
      const targetColumnName = quoteId(targetColumn.name, dialect, quoted);
      const constraintName = quoteId(
        `fk_${sourceTable.name}_${sourceColumn.name}_${fkIndex++}`,
        dialect,
        quoted
      );

      let alterSql = `ALTER TABLE ${sourceTableName} ADD CONSTRAINT ${constraintName} FOREIGN KEY (${sourceColumnName}) REFERENCES ${targetTableName} (${targetColumnName})`;
      if (rel.onDelete) alterSql += ` ON DELETE ${rel.onDelete}`;
      if (rel.onUpdate) alterSql += ` ON UPDATE ${rel.onUpdate}`;
      alterSql += ';';
      ddlStatements.push(alterSql);
    }
  }

  const rawSql = ddlStatements.join('\n\n');

  try {
    const formatterDialect =
      dialect === 'mysql' || dialect === 'mariadb'
        ? 'mysql'
        : dialect === 'sqlite'
        ? 'sqlite'
        : dialect === 'sqlserver'
        ? 'transactsql'
        : 'postgresql';

    return format(rawSql, {
      language: formatterDialect,
      keywordCase: 'upper',
      tabWidth: 2,
    });
  } catch {
    return rawSql;
  }
}
